    <h1>Tentang CompHub</h1>
    <p class="lead">Katalog lomba, webinar, dan seminar yang dikurasi dari sumber resmi.</p>

    <h2>Mengapa katalog ini ada</h2>
    <p>Informasi kegiatan mahasiswa tersebar di media sosial, grup percakapan, dan poster. CompHub mengumpulkannya di satu tempat agar mudah dicari, disaring, dan disimpan.</p>

    <h2>Cara data masuk</h2>
    <ul>
        <li>Setiap kegiatan berasal dari halaman resmi penyelenggara atau sumber yang dapat diperiksa.</li>
        <li>Entri mencantumkan penyelenggara, URL sumber, dan tanggal pemeriksaan.</li>
        <li>Tenggat yang belum dipastikan ditandai "Tenggat belum dipastikan".</li>
        <li>Kegiatan yang sudah tutup tidak tampil sebagai kegiatan yang masih buka.</li>
    </ul>

    <h2>Akses</h2>
    <p>Ringkasan kegiatan terbuka untuk umum. Detail lengkap, tautan pendaftaran, simpan, dan notifikasi memerlukan akun.</p>

