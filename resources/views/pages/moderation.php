<article class="prose">
    <h1>Kebijakan kurasi</h1>
    <p class="lead">Aturan yang dipakai saat memeriksa dan menayangkan kegiatan.</p>

    <div class="alert alert-info" role="note">
        <strong>Kegiatan ditayangkan setelah diperiksa manual.</strong>
        Penyedia belum dapat menerbitkan kegiatan sendiri.
    </div>

    <h2>Sumber yang dipakai</h2>
    <ul>
        <li>Halaman resmi penyelenggara.</li>
        <li>Pengumuman resmi kampus atau lembaga.</li>
        <li>Dokumen sumber yang disediakan pengelola katalog.</li>
    </ul>

    <h2>Yang diperiksa</h2>
    <ul>
        <li>Nama dan identitas penyelenggara.</li>
        <li>Tanggal pelaksanaan dan tenggat pendaftaran.</li>
        <li>Tautan pendaftaran dan tautan sumber.</li>
        <li>Apakah tautan masih aktif saat diperiksa.</li>
    </ul>

    <h2>Tenggat yang belum pasti</h2>
    <p>Jika penyelenggara belum mencantumkan tenggat, entri menampilkan "Tenggat belum dipastikan" dan tanggal perkiraan. Status buka tidak diklaim sebagai fakta.</p>

    <h2>Kegiatan yang sudah tutup</h2>
    <p>Kegiatan yang tenggatnya lewat tetap tersedia sebagai arsip, tetapi tidak tampil di daftar kegiatan buka.</p>
